export function isFreeEmailDomain(domain: string | null | undefined): boolean {
	const bare = (domain ?? "")
		.trim()
		.toLowerCase()
		.replace(/^www\./, "");
	return FREE_EMAIL_DOMAINS.has(bare);
}

