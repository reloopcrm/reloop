export function isPlatformDomain(domain: string | null | undefined): boolean {
	const bare = (domain ?? "")
		.trim()
		.toLowerCase()
		.replace(/^www\./, "");
	return PLATFORM_DOMAINS.some(
		(platform) => bare === platform || bare.endsWith(`.${platform}`),
	);
}
